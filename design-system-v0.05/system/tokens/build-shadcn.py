#!/usr/bin/env python3
"""Build the shadcn/Tailwind v4 theme adapter from the canonical GMD token JSON."""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "tokens.json"
OUTPUT = HERE / "shadcn.css"


def resolve(document: dict, path):
    if not isinstance(path, str) or not path.startswith(("reference.", "semantic.", "component.")):
        return path
    value = document
    for part in path.split("."):
        if not isinstance(value, dict) or part not in value:
            raise ValueError(f"Unresolved token reference: {path}")
        value = value[part]
    if isinstance(value, str) and value.startswith(("reference.", "semantic.", "component.")):
        return resolve(document, value)
    return value

def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8-sig"))
    semantic = data["semantic"]["color"]
    refs = data["reference"]["color"]

    # shadcn primitives: action pink is primary; Nile remains the link/ring color.
    mapping = {
        "background": semantic["canvas"],
        "foreground": semantic["text"],
        "card": semantic["surface"],
        "card-foreground": semantic["text"],
        "popover": semantic["surfaceRaised"],
        "popover-foreground": semantic["text"],
        "primary": semantic["action"],
        "primary-foreground": semantic["onAction"],
        "secondary": semantic["surfaceSubtle"],
        "secondary-foreground": semantic["text"],
        "muted": semantic["surfaceSubtle"],
        "muted-foreground": semantic["textMuted"],
        "accent": semantic["selection"],
        "accent-foreground": semantic["text"],
        "destructive": semantic["error"],
        "destructive-foreground": semantic["textInverse"],
        "border": semantic["border"],
        "input": semantic["border"],
        "ring": semantic["focus"],
        "sidebar": semantic["surfaceSubtle"],
        "sidebar-foreground": semantic["text"],
        "sidebar-primary": semantic["primary"],
        "sidebar-primary-foreground": semantic["onPrimary"],
        "sidebar-accent": semantic["selection"],
        "sidebar-accent-foreground": semantic["text"],
        "sidebar-border": semantic["border"],
        "sidebar-ring": semantic["focus"],
        **{f"chart-{i}": semantic[f"chart{i}"] for i in range(1, 6)},
    }
    radius = data["semantic"]["shape"]["radius"]
    resolved = {name: resolve(data, value) for name, value in mapping.items()}
    for name, value in resolved.items():
        if not isinstance(value, str) or not value.startswith("#"):
            raise ValueError(f"Expected resolved hex color for {name}, got {value!r}")

    extras = {
        "gmd-ink": refs["ink"],
        "gmd-paper": refs["paper"],
        "gmd-warm": refs["warm"],
        "gmd-nile": refs["nile600"],
        "gmd-nile-soft": refs["nile100"],
        "gmd-link": semantic["primary"],
        "gmd-selected": semantic["selection"],
        "gmd-control-accent": semantic["primary"],
        "gmd-action": semantic["action"],
        "gmd-action-hover": semantic["actionHover"],
        "gmd-action-active": semantic["actionActive"],
        "gmd-success": semantic["success"],
        "gmd-success-surface": semantic["successSurface"],
        "gmd-warning": semantic["warning"],
        "gmd-warning-surface": semantic["warningSurface"],
        "gmd-error": semantic["error"],
        "gmd-error-surface": semantic["errorSurface"],
        "gmd-disabled-text": semantic["disabledText"],
        "gmd-disabled-surface": semantic["disabledSurface"],
        "gmd-disabled-border": semantic["disabledBorder"],
    }
    resolved_extras = {name: resolve(data, value) for name, value in extras.items()}
    fonts = {
        "ui": resolve(data, data["semantic"]["type"]["ui"]),
        "prose": resolve(data, data["semantic"]["type"]["reading"]),
        "display": resolve(data, data["semantic"]["type"]["display"]),
    }

    lines = [
        "/* Generated by build-shadcn.py from tokens.json; do not hand-edit. */",
        ":root {",
        '  color-scheme: light;',
    ]
    lines += [f"  --{name}: {value};" for name, value in resolved.items()]
    lines += [f"  --{name}: {value};" for name, value in resolved_extras.items()]
    lines += [f"  --gmd-font-{name}: '{value}';" for name, value in fonts.items()]
    lines += [
        f"  --radius: {radius}px;",
        "}",
        "",
        "/* Tailwind CSS v4 utility mappings used by shadcn/ui. */",
        "@theme inline {",
    ]
    lines += [f"  --color-{name}: var(--{name});" for name in resolved]
    lines += [
        "  --color-link: var(--gmd-link);",
        "  --color-selected: var(--gmd-selected);",
        "  --color-control-accent: var(--gmd-control-accent);",
        "  --font-ui: var(--gmd-font-ui);",
        "  --font-prose: var(--gmd-font-prose);",
        "  --font-display: var(--gmd-font-display);",
    ]
    lines += [
        "  --radius-sm: var(--radius);",
        "  --radius-md: var(--radius);",
        "  --radius-lg: var(--radius);",
        "  --radius-xl: var(--radius);",
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT.name}: {len(resolved)} shadcn roles, {len(resolved_extras)} GMD roles")


if __name__ == "__main__":
    main()




