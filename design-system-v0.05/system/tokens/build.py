"""Generate current browser bindings; fail on missing source aliases."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).parent
data = json.loads((ROOT / 'tokens.json').read_text(encoding='utf-8'))

def kebab(key):
    key = re.sub(r'([a-z])([A-Z0-9])', r'\1-\2', key)
    return key.lower()

def source(path):
    node = data
    for part in path.split('.'):
        node = node[part]
    return node

def color_alias(path):
    source(path)
    layer, category, key = path.split('.')
    return 'var(--gmd-' + ('ref-color-' if layer == 'reference' else 'color-') + kebab(key) + ')'

values = {}
def emit(name, value):
    assert name not in values, name
    values[name] = value

for key, value in data['reference']['color'].items():
    emit('ref-color-' + kebab(key), value)
for key, value in data['semantic']['color'].items():
    emit('color-' + kebab(key), color_alias(value))
for key, ref in {'ink':'ink','paper':'paper','warm':'warm','nile':'nile600','pink':'action'}.items():
    emit('color-' + key, color_alias('reference.color.' + ref))
type_names = {'display':'display','ui':'ui','reading':'reading','arabicHeading':'ar-heading','arabicBody':'ar-body','pixelAccent':'pixel'}
for key, path in data['semantic']['type'].items():
    family = source(path)
    fallback = 'serif' if key in ['display','reading','arabicBody'] else 'sans-serif'
    emit('type-' + type_names[key], json.dumps(family) + ', ' + fallback)
for key, size in data['semantic']['typeSizePx'].items():
    emit('type-size-' + kebab(key), str(size / 16).rstrip('0').rstrip('.') + 'rem')
for key, value in data['semantic']['lineHeight'].items():
    emit('type-line-' + kebab(key), value)
for key, size in data['semantic']['space'].items():
    emit('space-' + key, str(size / 16).rstrip('0').rstrip('.') + 'rem')
emit('shape-radius', str(data['semantic']['shape']['radius']))
emit('shape-border', str(data['semantic']['shape']['borderWidth']) + 'px')
for key, value in data['component']['depth'].items():
    emit('depth-' + ('default' if key == 'rest' else key), value)
emit('depth-none', 'none')
for key, value in data['component']['focus'].items():
    emit('focus-' + key.removesuffix('Px'), str(value) + ('px' if key.endswith('Px') else ''))
for key, value in data['reference']['breakpointsPx'].items():
    emit('breakpoint-' + key, str(value) + 'px')
for key, value in data['semantic']['motion'].items():
    emit('motion-' + key, str(value) + 'ms')
emit('motion-ease', 'cubic-bezier(0.2, 0.7, 0.2, 1)')
for key, value in {'ar-h1-max':data['rtl']['arabicHeadingMaxPx'],'ar-h2-max':data['rtl']['arabicSectionHeadingMaxPx'],'ar-h1-mobile-max':data['rtl']['arabicMobileHeadingMaxPx']}.items():
    emit('type-' + key, str(value / 16).rstrip('0').rstrip('.') + 'rem')
component_names = {'buttonAction':'button-action-background','buttonActionText':'button-action-text','buttonPrimary':'button-primary-background','buttonPrimaryText':'button-primary-text','fieldBackground':'control-background','fieldText':'control-text','fieldBorder':'field-border','fieldFocus':'field-focus','cardBackground':'card-background','cardBorder':'card-border-color','disabledBackground':'disabled-background'}
for key, path in data['component']['color'].items():
    emit('component-' + component_names[key], color_alias(path))
emit('component-control-height', str(data['component']['control']['heightPx'] / 16).rstrip('0').rstrip('.') + 'rem')
emit('component-control-border', 'var(--gmd-shape-border) solid var(--gmd-color-border)')
emit('component-button-depth', 'var(--gmd-depth-default)')
emit('component-card-border', 'var(--gmd-shape-border) solid var(--gmd-component-card-border-color)')
css = '/* Generated by build.py from tokens.json. */\n:root {\n'
css += ''.join(f'  --gmd-{key}: {value};\n' for key, value in values.items()) + '}\n'
css += '@media(prefers-reduced-motion:reduce){:root{--gmd-motion-fast:0ms;--gmd-motion-standard:0ms;--gmd-motion-slow:0ms}}\n'
(ROOT / 'tokens.css').write_text(css, encoding='utf-8')
print(f'Generated {len(values)} unique CSS bindings; source aliases validated.')
